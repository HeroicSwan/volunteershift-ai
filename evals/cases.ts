const WEEK = ["2026-09-14", "2026-09-15", "2026-09-16", "2026-09-17", "2026-09-18", "2026-09-19", "2026-09-20"];

function availability(days: readonly DayOfWeek[] = DAYS, start = "08:00", end = "18:00") {
  return Object.fromEntries(days.map((day) => [day, [{ start, end }]])) as Worker["availability"];
}

function worker(id: string, overrides: Partial<Worker> = {}): Worker {
  return {
    id,
    name: id.split("-").map((part) => part[0].toUpperCase() + part.slice(1)).join(" "),
    email: `${id}@harborlight.org`,
    workerType: "volunteer",
    roles: ["General Support"],
    availability: availability(),
    preferredDays: [],
    preferredRoles: [],
    maxShiftsPerWeek: 5,
    desiredHoursPerWeek: 16,
    maxHoursPerWeek: 20,
    reliabilityScore: 4,
    notes: "Evaluation roster member",
    ...overrides,
  };
}

function paid(id: string, overrides: Partial<Worker> = {}) {
  return worker(id, {
    workerType: "paid_employee",
    employmentType: "full_time",
    desiredHoursPerWeek: 40,
    maxHoursPerWeek: 40,
    maxShiftsPerWeek: 5,
    hourlyRate: 22,
    ...overrides,
  });
}

function supervisor(id: string, overrides: Partial<Worker> = {}) {
  return paid(id, { workerType: "supervisor", roles: ["General Support", "Manager"], hourlyRate: 28, ...overrides });
}

function shift(id: string, overrides: Partial<Shift> = {}): Shift {
  return {
    id,
    title: id.split("-").map((part) => part[0].toUpperCase() + part.slice(1)).join(" "),
    date: WEEK[0],
    startTime: "09:00",
    endTime: "13:00",
    location: "Harborlight Community Center",
    requiredRole: "General Support",
    requiredWorkers: 1,
    requiresSupervisor: false,
    priority: "Normal",
    notes: "Evaluation shift",
    ...overrides,
  };
}

